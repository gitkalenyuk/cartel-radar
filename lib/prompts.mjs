export function marketLine(markets) {
  const langs = (markets?.langs || []).join(", ") || "усі";
  const regions = (markets?.regions || []).join(", ") || "усі";
  return `Цільові мови пошуку: ${langs}. Цільові країни/ринки: ${regions}.`;
}

