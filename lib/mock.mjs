/** Детермінована відповідь залежно від режиму, вказаного у промпті. */
export function mockComplete(messages, opts = {}) {
  const text = messages.map((m) => (typeof m.content === "string" ? m.content : JSON.stringify(m.content))).join("\n");
  const mode = (text.match(/\[MODE:(\w+)\]/) || [])[1] || "free";
  const candMatch = text.match(/КАНДИДАТ:\s*(.+)/);
  const seed = opts.seed || hash(text).toString(36);

  if (mode === "discovery") {
    const idx = parseInt((text.match(/\[BATCH:(\d+)\]/) || [])[1] || "0", 10);
    const count = Number(opts.count || 12);
    return JSON.stringify({ candidates: Array.from({ length: count }, (_, i) => candidate(idx * count + i, seed + i)) });
  }
  if (mode === "screening") {
    const name = candMatch ? candMatch[1].trim() : "Ніша (демо)";
    return JSON.stringify(screening(name, seed));
  }
  if (mode === "deepdive") {
    const name = candMatch ? candMatch[1].trim() : "Ніша (демо)";
    return JSON.stringify(deepdive(name, seed));
  }
  if (mode === "channel") return JSON.stringify(channelAnalysis((text.match(/КАНАЛ:\s*(.+)/) || [, "Демо-канал"])[1].trim()));
  if (mode === "gap") return JSON.stringify(gapScan((text.match(/СІД:\s*(.+)/) || [, "демо"])[1].trim()));
  if (mode === "thumbs") return JSON.stringify(thumbsAnalysis((text.match(/(?:ДЖЕРЕЛО|КАНАЛ|ВІДЕО):\s*(.+)/) || [, "демо-канал"])[1].trim()));
  if (mode === "video") return JSON.stringify(videoLab((text.match(/ВІДЕО:\s*(.+)/) || [, "https://youtu.be/demo"])[1].trim()));
  if (mode === "rationale") return JSON.stringify({ rationale: "Демо-обґрунтування: ніша має попит, слабку конкуренцію та високу монетизованість.", confidence: 7 });
  return "Демо-відповідь локального рушія. Усе працює: підключіть справжній провайдер у вкладці «Провайдери».";
}

export async function* mockStream(messages, opts) {
  const full = mockComplete(messages, opts);
  const size = 220;
  for (let i = 0; i < full.length; i += size) {
    await new Promise((r) => setTimeout(r, 8));
    yield { text: full.slice(i, i + size), usage: null, done: false };
  }
  yield { text: "", usage: { promptTokens: Math.ceil(JSON.stringify(messages).length / 4), completionTokens: Math.ceil(full.length / 4) }, done: true };
}
